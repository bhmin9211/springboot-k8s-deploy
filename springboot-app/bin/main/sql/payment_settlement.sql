CREATE DATABASE IF NOT EXISTS k8s_dashboard DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;

CREATE TABLE IF NOT EXISTS k8s_dashboard.PAYMENT_REQUESTS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    IDEMPOTENCY_KEY VARCHAR(100) NOT NULL,
    REQUEST_NO VARCHAR(40) NOT NULL,
    AMOUNT DECIMAL(15, 2) NOT NULL,
    REQUESTED_BY VARCHAR(100) NOT NULL,
    APPROVED_BY VARCHAR(100),
    APPROVED_AT DATETIME,
    REJECTED_BY VARCHAR(100),
    REJECTED_AT DATETIME,
    REJECT_REASON VARCHAR(500),
    FAILURE_REASON VARCHAR(500),
    RETRY_COUNT INT NOT NULL DEFAULT 0,
    STATUS VARCHAR(30) NOT NULL,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NOT NULL,
    CONSTRAINT UK_PAYMENT_REQUESTS_IDEMPOTENCY_KEY UNIQUE (IDEMPOTENCY_KEY),
    CONSTRAINT UK_PAYMENT_REQUESTS_REQUEST_NO UNIQUE (REQUEST_NO)
);

CREATE TABLE IF NOT EXISTS k8s_dashboard.PAYMENT_STATUS_HISTORIES (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    PAYMENT_REQUEST_ID BIGINT NOT NULL,
    FROM_STATUS VARCHAR(30),
    TO_STATUS VARCHAR(30) NOT NULL,
    REASON VARCHAR(500),
    CHANGED_BY VARCHAR(100) NOT NULL,
    CREATED_AT DATETIME NOT NULL,
    INDEX IDX_PAYMENT_STATUS_HISTORIES_REQUEST_ID (PAYMENT_REQUEST_ID),
    CONSTRAINT FK_PAYMENT_STATUS_HISTORIES_REQUEST
        FOREIGN KEY (PAYMENT_REQUEST_ID) REFERENCES k8s_dashboard.PAYMENT_REQUESTS (ID)
);

CREATE TABLE IF NOT EXISTS k8s_dashboard.AUDIT_LOGS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    ACTOR_ID VARCHAR(100) NOT NULL,
    ACTION_TYPE VARCHAR(50) NOT NULL,
    TARGET_TYPE VARCHAR(50) NOT NULL,
    TARGET_ID BIGINT NOT NULL,
    BEFORE_VALUE TEXT,
    AFTER_VALUE TEXT,
    IP_ADDRESS VARCHAR(50),
    CREATED_AT DATETIME NOT NULL,
    INDEX IDX_AUDIT_LOGS_TARGET (TARGET_TYPE, TARGET_ID),
    INDEX IDX_AUDIT_LOGS_ACTOR (ACTOR_ID)
);

CREATE TABLE IF NOT EXISTS k8s_dashboard.SETTLEMENTS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    PAYMENT_REQUEST_ID BIGINT NOT NULL,
    GROSS_AMOUNT DECIMAL(15, 2) NOT NULL,
    FEE_AMOUNT DECIMAL(15, 2) NOT NULL,
    SETTLEMENT_AMOUNT DECIMAL(15, 2) NOT NULL,
    SETTLEMENT_STATUS VARCHAR(30) NOT NULL,
    SETTLEMENT_DUE_DATE DATE NOT NULL,
    CREATED_AT DATETIME NOT NULL,
    UPDATED_AT DATETIME NOT NULL,
    CONSTRAINT UK_SETTLEMENTS_PAYMENT_REQUEST_ID UNIQUE (PAYMENT_REQUEST_ID),
    CONSTRAINT FK_SETTLEMENTS_PAYMENT_REQUEST
        FOREIGN KEY (PAYMENT_REQUEST_ID) REFERENCES k8s_dashboard.PAYMENT_REQUESTS (ID)
);

CREATE TABLE IF NOT EXISTS k8s_dashboard.RECONCILIATION_RESULTS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    SETTLEMENT_ID BIGINT,
    EXTERNAL_TRANSACTION_ID VARCHAR(100) NOT NULL,
    INTERNAL_AMOUNT DECIMAL(15, 2),
    EXTERNAL_AMOUNT DECIMAL(15, 2),
    INTERNAL_STATUS VARCHAR(30),
    EXTERNAL_STATUS VARCHAR(30),
    RESULT_TYPE VARCHAR(30) NOT NULL,
    MISMATCH_REASON VARCHAR(500),
    CREATED_AT DATETIME NOT NULL,
    INDEX IDX_RECONCILIATION_RESULTS_SETTLEMENT_ID (SETTLEMENT_ID),
    INDEX IDX_RECONCILIATION_RESULTS_RESULT_TYPE (RESULT_TYPE),
    CONSTRAINT FK_RECONCILIATION_RESULTS_SETTLEMENT
        FOREIGN KEY (SETTLEMENT_ID) REFERENCES k8s_dashboard.SETTLEMENTS (ID)
);
